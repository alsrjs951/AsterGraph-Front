"""Regenerate approved AG Aperture artwork from the saved round-2 outlines.
Requires fontTools only for offline path bounds/normalization; no runtime dependency.
"""
from pathlib import Path
import json, re, shutil, xml.etree.ElementTree as ET
from fontTools.svgLib.path import parse_path
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.transformPen import TransformPen
P=Path(__file__).resolve().parent
ROOT=P.parents[2]
OUT=ROOT/'public/brand'
OUT.mkdir(exist_ok=True)
NS='{http://www.w3.org/2000/svg}'
source=ET.parse(ROOT/'docs/brand/logo-review-round2/iterations/a-v2.svg').getroot()
normal=source.find(NS+'path').attrib['d']
# Increase interior counter by about 1 unit on reverse; outer silhouette is preserved.
reverse=normal.replace('151.094L128 86L73.729 180H170.321L153 150','149.939L128 88L75.461 179H170.898L154.155 150')
# 16–24px cut: 32-unit aperture, rather than the master 24-unit aperture.
small=normal.replace('193.879 126H151.094','191.570 122H148.785').replace('H170.321L153 150H207.566','H168.011L153 154H209.876')
root=ET.parse(ROOT/'docs/brand/logo-review-round2/iterations/wordmark.svg').getroot()
raw=' '.join(el.attrib['d'] for el in root.iter(NS+'path'))
bounds=BoundsPen(None);parse_path(raw,bounds)
x0,y0,x1,y1=bounds.bounds
pen=SVGPathPen(None);parse_path(raw,TransformPen(pen,(1,0,0,1,-x0,-y0)))
word=re.sub(r'-?\d+\.\d+',lambda m:format(float(m[0]),'.3f').rstrip('0').rstrip('.'),pen.getCommands())
w=round(x1-x0,3);h=round(y1-y0,3)

def svg(body,view='0 0 256 256',title='AsterGraph — AG Aperture'):
 return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{view}" role="img" aria-label="AsterGraph"><title>{title}</title>{body}</svg>\n'
def path(d,c):return f'<path fill="{c}" d="{d}"/>'
for suffix,colour,d in [('black','#000000',normal),('white','#ffffff',reverse),('light','#2458c6',normal),('dark','#78aaff',reverse),('small','#000000',small)]:
 (OUT/f'symbol-{suffix}.svg').write_text(svg(path(d,colour)))
for mode,col,ink,d in [('light','#2458c6','#17263c',normal),('dark','#78aaff','#eef3f9',reverse),('black','#000000','#000000',normal),('white','#ffffff','#ffffff',reverse)]:
 # Optical cap alignment: symbol height 126, wordmark including descender 127.
 horizontal=f'<g transform="translate(0 22) scale(.7)">{path(d,col)}</g><g transform="translate(204 60)">{path(word,ink)}</g>'
 (OUT/f'horizontal-{mode}.svg').write_text(svg(horizontal,f'0 0 {w+220:.3f} 220'))
 (OUT/f'wordmark-{mode}.svg').write_text(svg(path(word,ink),f'-2 -2 {w+4:.3f} {h+4:.3f}'))
 stacked=f'<g transform="translate({(w+40-256)/2:.3f} 0)">{path(d,col)}</g><g transform="translate(20 286)">{path(word,ink)}</g>'
 (OUT/f'stacked-{mode}.svg').write_text(svg(stacked,f'0 0 {w+40:.3f} {h+310:.3f}'))
# Favicon keeps established URLs, widened counter and a tight but padded 224-square crop.
(ROOT/'public/astergraph.svg').write_text(svg(path(small,'#78aaff'),'16 16 224 224'))
(ROOT/'public/astergraph-light.svg').write_text(svg(path(small,'#2458c6'),'16 16 224 224'))
# App source and files share these generated outlines. No runtime font or asset fetch.
(ROOT/'src/components/brandPaths.ts').write_text('/** Generated by docs/brand/astergraph-final/build_assets.py. */\n'+''.join(f'export const {key} = {json.dumps(value)};\n' for key,value in [('BRAND_MARK',normal),('BRAND_MARK_REVERSED',reverse),('BRAND_WORDMARK',word),('BRAND_WORDMARK_VIEWBOX',f'-2 -2 {w+4:.3f} {h+4:.3f}')]))
shutil.copyfile(ROOT/'docs/brand/logo-review-round2/fonts/OFL.txt',P/'FONT-LICENSE.txt')
print(f'Wrote approved masters; wordmark {w} x {h}; no live text.')
